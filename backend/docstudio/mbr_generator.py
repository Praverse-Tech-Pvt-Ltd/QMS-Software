"""
MBR skeleton generator and draft validator.

Layered and deterministic: template (stage_library) + product data (user-supplied).
AI wording is applied later and optionally; this module never fabricates limits.
"""
from .stage_library import LIBRARY, LIBRARY_STATUS


class UnknownDosageForm(ValueError):
    pass


def build_skeleton(product, dosage_form, batch_size='', parameters=None, excluded_stage_keys=None):
    """
    Return {product, dosage_form, library_status, steps:[...], warnings:[...]}.

    parameters: optional {stage_key: {'expected_range': '98.0-102.0', 'notes': '...'}} supplied by the user.
    Stages in excluded_stage_keys are omitted (e.g. coating) with a warning recording the exclusion.
    """
    if dosage_form not in LIBRARY:
        raise UnknownDosageForm(f'Unknown dosage form "{dosage_form}". Available: {", ".join(LIBRARY)}')
    parameters = parameters or {}
    excluded = set(excluded_stage_keys or [])
    template = LIBRARY[dosage_form]
    steps, warnings = [], []
    n = 0
    for stage in template['stages']:
        if stage['key'] in excluded:
            warnings.append(
                f'Stage "{stage["title"]}" excluded by author - document the justification in the MBR header.')
            continue
        n += 1
        p = parameters.get(stage['key'], {})
        steps.append({
            'step_number': n,
            'stage_key': stage['key'],
            'title': stage['title'],
            'instruction': stage['instruction'],
            'records': list(stage['records']),
            'is_critical': stage['critical'],
            'esig_required': stage['critical'],
            'ipqc_suggested': list(stage['ipqc']),
            'expected_range': p.get('expected_range', ''),
            'notes': p.get('notes', ''),
        })
    return {
        'product': product,
        'dosage_form': dosage_form,
        'dosage_form_label': template['label'],
        'batch_size': batch_size,
        'library_status': LIBRARY_STATUS,
        'steps': steps,
        'warnings': warnings,
    }


def validate_skeleton(skeleton, theoretical_yield=None, yield_formula=''):
    """
    Return {'blocking': [...], 'advisory': [...]}.
    An MBR must have zero blocking items before it can be sent for approval.
    """
    blocking, advisory = [], []
    steps = skeleton.get('steps', [])
    keys = {s.get('stage_key') for s in steps}
    form = skeleton.get('dosage_form')

    if not skeleton.get('product'):
        blocking.append('Product name is missing.')
    if not skeleton.get('batch_size'):
        blocking.append('Batch size is missing.')
    if theoretical_yield in (None, ''):
        blocking.append('Theoretical yield is not defined.')
    if not (yield_formula or '').strip():
        blocking.append('Yield calculation formula is not defined.')

    for must in ('line_clearance', 'yield_reconciliation', 'batch_review'):
        if must not in keys:
            blocking.append(f'Mandatory stage "{must}" is missing.')
    if form in LIBRARY:
        template_keys = {s['key'] for s in LIBRARY[form]['stages']}
        if 'dispensing' in template_keys and 'dispensing' not in keys:
            blocking.append('Mandatory stage "dispensing" is missing.')

    for s in steps:
        if s.get('is_critical') and not s.get('esig_required'):
            blocking.append(f'Step {s["step_number"]} ({s["title"]}) is critical but does not require e-signature.')
        if not s.get('records'):
            blocking.append(f'Step {s["step_number"]} ({s["title"]}) has no recorded fields.')
        if s.get('ipqc_suggested') and not s.get('expected_range'):
            advisory.append(
                f'Step {s["step_number"]} ({s["title"]}): IPQC parameters suggested '
                f'({", ".join(s["ipqc_suggested"])}) but no limits defined - add from the approved specification.')

    return {'blocking': blocking, 'advisory': advisory}


def persist_mbr(skeleton, version, user, theoretical_yield=None, yield_formula=''):
    """Create a draft MasterBatchRecord + MBRSteps."""
    from django.db import transaction
    from batch_records.models import MasterBatchRecord, MBRStep

    with transaction.atomic():
        mbr = MasterBatchRecord.objects.create(
            product=skeleton['product'],
            version=version,
            status='draft',
            theoretical_yield=theoretical_yield,
            yield_formula=yield_formula,
            description=(
                f'Generated by Document Studio from template "{skeleton["dosage_form"]}" '
                f'(library {LIBRARY_STATUS["version"]}, expert_reviewed={LIBRARY_STATUS["expert_reviewed"]}). '
                f'Batch size: {skeleton.get("batch_size", "")}.'),
            created_by=user,
            modified_by=user,
        )
        for s in skeleton['steps']:
            text = f'{s["title"]}: {s["instruction"]} Record: {"; ".join(s["records"])}.'
            if s.get('ipqc_suggested'):
                text += f' IPQC: {", ".join(s["ipqc_suggested"])}.'
            MBRStep.objects.create(
                mbr=mbr,
                step_number=s['step_number'],
                description=text,
                is_critical=s['is_critical'],
                esig_required=s['esig_required'],
                expected_range=s.get('expected_range', ''),
            )
    return mbr
